/**
 * Medya varlıklarının türlerini tanımlar.
 */
public enum AssetType {

    /** Görsel dosya */
    IMAGE,

    /** Video dosya */
    VIDEO,

    /** Ses dosyası */
    AUDIO,

    /** Müzik dosyası */
    MUSIC,

    /** Seslendirme dosyası */
    VOICEOVER,

    /** Küçük resim (thumbnail) */
    THUMBNAIL,

    /** Altyazı dosyası */
    SUBTITLE,

    /** Belge dosyası */
    DOCUMENT
}
